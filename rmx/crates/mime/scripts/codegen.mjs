// Generates crates/mime/src/generated.rs from Remix's generated mime tables, which Remix
// builds from mime-db with its own tie-breaking rules (standard over vendor types, then
// compressible, then IANA) and overrides (mp4, ico).
//
// Usage: node crates/mime/scripts/codegen.mjs <path to remix/packages/mime/src/generated>
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

let source = process.argv[2]
if (!source) throw new Error('pass the path to remix/packages/mime/src/generated')

let mimeTypes = readFileSync(join(source, 'mime-types.ts'), 'utf-8')
let entries = [...mimeTypes.matchAll(/^  '?([^':]+)'?: '([^']+)',$/gm)].map((m) => [m[1], m[2]])
entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))

let compressible = readFileSync(join(source, 'compressible-mime-types.ts'), 'utf-8')
let types = [...compressible.matchAll(/^  '([^']+)',$/gm)].map((m) => m[1]).sort()

let out = `// DO NOT EDIT. Generated by scripts/codegen.mjs from Remix's mime tables (mime-db).

/// Extension to MIME type, sorted by extension for binary search.
pub(crate) static MIME_TYPES: &[(&str, &str)] = &[
${entries.map(([ext, type]) => `    ("${ext}", "${type}"),`).join('\n')}
];

/// Types mime-db marks compressible that the generic rules (\`text/*\`, \`+json\`, \`+text\`,
/// \`+xml\`) do not cover, sorted.
pub(crate) static COMPRESSIBLE_MIME_TYPES: &[&str] = &[
${types.map((type) => `    "${type}",`).join('\n')}
];
`
let target = join(dirname(fileURLToPath(import.meta.url)), '../src/generated.rs')
writeFileSync(target, out)
console.log(`${entries.length} extensions, ${types.length} compressible types`)
